import duckdb
c = duckdb.connect()
c.execute("""CREATE TABLE OFFICE(OFFICE_ID INT, OFFICE_NUMBER VARCHAR,
             ROW_EFFECTIVE_DATETIME DATE, ROW_EXPIRATION_DATETIME DATE, ROW_UPDATE_DATETIME DATE)""")
c.execute("""CREATE TABLE DEPARTMENT(DEPARTMENT_ID INT, DEPARTMENT_NUMBER VARCHAR,
             ROW_EFFECTIVE_DATETIME DATE, ROW_EXPIRATION_DATETIME DATE, ROW_UPDATE_DATETIME DATE)""")
c.execute("""CREATE TABLE OFFICE_DEPARTMENT_STG(OFFICE_NUMBER VARCHAR, DEPARTMENT_NUMBER VARCHAR,
             PHONE_NUMBER VARCHAR, ROW_EFFECTIVE_DATETIME DATE, ROW_EXPIRATION_DATETIME DATE,
             CURRENT_RECORD_INDICATOR VARCHAR)""")

# one association spanning two OFFICE versions
c.executemany("INSERT INTO OFFICE VALUES (?,?,?,?,?)", [
  (501,'O001','2024-01-01','2024-05-01','2024-01-01'),
  (502,'O001','2024-05-01','9999-12-31','2024-05-01')])
c.execute("INSERT INTO DEPARTMENT VALUES (701,'D001',DATE '2024-01-01',DATE '9999-12-31',DATE '2024-01-01')")
c.execute("INSERT INTO OFFICE_DEPARTMENT_STG VALUES ('O001','D001','555-0100',DATE '2024-01-01',DATE '9999-12-31','Y')")

CTE = """
WITH fk_bounds AS (
  SELECT DISTINCT OFFICE_NUMBER, DEPARTMENT_NUMBER, b FROM (
    SELECT s.OFFICE_NUMBER, s.DEPARTMENT_NUMBER, s.ROW_EFFECTIVE_DATETIME  AS b FROM OFFICE_DEPARTMENT_STG s
    UNION ALL SELECT s.OFFICE_NUMBER, s.DEPARTMENT_NUMBER, s.ROW_EXPIRATION_DATETIME FROM OFFICE_DEPARTMENT_STG s
    UNION ALL SELECT s.OFFICE_NUMBER, s.DEPARTMENT_NUMBER, pa.ROW_EFFECTIVE_DATETIME
              FROM OFFICE_DEPARTMENT_STG s JOIN OFFICE pa ON TRIM(s.OFFICE_NUMBER)=TRIM(pa.OFFICE_NUMBER)
    UNION ALL SELECT s.OFFICE_NUMBER, s.DEPARTMENT_NUMBER, pa.ROW_EXPIRATION_DATETIME
              FROM OFFICE_DEPARTMENT_STG s JOIN OFFICE pa ON TRIM(s.OFFICE_NUMBER)=TRIM(pa.OFFICE_NUMBER)
    UNION ALL SELECT s.OFFICE_NUMBER, s.DEPARTMENT_NUMBER, pa.ROW_EFFECTIVE_DATETIME
              FROM OFFICE_DEPARTMENT_STG s JOIN DEPARTMENT pa ON TRIM(s.DEPARTMENT_NUMBER)=TRIM(pa.DEPARTMENT_NUMBER)
    UNION ALL SELECT s.OFFICE_NUMBER, s.DEPARTMENT_NUMBER, pa.ROW_EXPIRATION_DATETIME
              FROM OFFICE_DEPARTMENT_STG s JOIN DEPARTMENT pa ON TRIM(s.DEPARTMENT_NUMBER)=TRIM(pa.DEPARTMENT_NUMBER))),
fk_intervals AS (
  SELECT OFFICE_NUMBER, DEPARTMENT_NUMBER, b AS ROW_EFFECTIVE_DATETIME,
         LEAD(b) OVER (PARTITION BY OFFICE_NUMBER, DEPARTMENT_NUMBER ORDER BY b) AS ROW_EXPIRATION_DATETIME
  FROM fk_bounds),
fk_split_stg AS (
  SELECT s.*, fi.ROW_EFFECTIVE_DATETIME AS SPLIT_ROW_EFFECTIVE_DATETIME,
              fi.ROW_EXPIRATION_DATETIME AS SPLIT_ROW_EXPIRATION_DATETIME
  FROM fk_intervals fi
  JOIN OFFICE_DEPARTMENT_STG s ON s.OFFICE_NUMBER=fi.OFFICE_NUMBER AND s.DEPARTMENT_NUMBER=fi.DEPARTMENT_NUMBER
   AND s.ROW_EFFECTIVE_DATETIME <= fi.ROW_EFFECTIVE_DATETIME
   AND s.ROW_EXPIRATION_DATETIME >  fi.ROW_EFFECTIVE_DATETIME
  WHERE fi.ROW_EXPIRATION_DATETIME IS NOT NULL)
"""

print("=== what fk_split_stg produces (the split itself) ===")
for r in c.execute(CTE + """
  SELECT OFFICE_NUMBER, SPLIT_ROW_EFFECTIVE_DATETIME, SPLIT_ROW_EXPIRATION_DATETIME,
         ROW_EFFECTIVE_DATETIME AS orig_eff, ROW_EXPIRATION_DATETIME AS orig_exp
  FROM fk_split_stg ORDER BY 2""").fetchall(): print("   ", r)
print("   -> correctly split into two sub-intervals. Note orig_eff/orig_exp are IDENTICAL on both.\n")

print("=== the generated final SELECT, transcribed verbatim ===")
FINAL = CTE + """
SELECT stg.OFFICE_NUMBER, stg.DEPARTMENT_NUMBER,
       stg.ROW_EFFECTIVE_DATETIME   AS ROW_EFFECTIVE_DATETIME,     -- line 76: UNSPLIT
       stg.ROW_EXPIRATION_DATETIME  AS ROW_EXPIRATION_DATETIME,    -- line 77: UNSPLIT
       p_office_id.OFFICE_ID, p_department_id.DEPARTMENT_ID
FROM fk_split_stg stg
LEFT JOIN (SELECT OFFICE_ID, OFFICE_NUMBER, ROW_EFFECTIVE_DATETIME, ROW_EXPIRATION_DATETIME FROM OFFICE
           QUALIFY ROW_NUMBER() OVER (PARTITION BY OFFICE_NUMBER, ROW_EFFECTIVE_DATETIME ORDER BY ROW_UPDATE_DATETIME DESC)=1) p_office_id
  ON  stg.OFFICE_NUMBER = p_office_id.OFFICE_NUMBER
  AND stg.SPLIT_ROW_EFFECTIVE_DATETIME >= p_office_id.ROW_EFFECTIVE_DATETIME
  AND stg.SPLIT_ROW_EFFECTIVE_DATETIME <  p_office_id.ROW_EXPIRATION_DATETIME
LEFT JOIN (SELECT DEPARTMENT_ID, DEPARTMENT_NUMBER, ROW_EFFECTIVE_DATETIME, ROW_EXPIRATION_DATETIME FROM DEPARTMENT
           QUALIFY ROW_NUMBER() OVER (PARTITION BY DEPARTMENT_NUMBER, ROW_EFFECTIVE_DATETIME ORDER BY ROW_UPDATE_DATETIME DESC)=1) p_department_id
  ON  stg.DEPARTMENT_NUMBER = p_department_id.DEPARTMENT_NUMBER
  AND stg.SPLIT_ROW_EFFECTIVE_DATETIME >= p_department_id.ROW_EFFECTIVE_DATETIME
  AND stg.SPLIT_ROW_EFFECTIVE_DATETIME <  p_department_id.ROW_EXPIRATION_DATETIME
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY stg.OFFICE_NUMBER, stg.DEPARTMENT_NUMBER, stg.ROW_EFFECTIVE_DATETIME   -- line 137: UNSPLIT
    ORDER BY stg.ROW_EXPIRATION_DATETIME DESC NULLS LAST) = 1
"""
rows = c.execute(FINAL).fetchall()
for r in rows: print("   ", r)
print(f"\n   rows leaving the query: {len(rows)}  (the split produced 2)")
print("   -> the QUALIFY partitions on the UNSPLIT effective date, which is identical on every")
print("      sub-interval, so it collapses them back to ONE row — and that row carries the")
print("      UNSPLIT dates. The split is computed, used only to pick an FK, then discarded.\n")

print("=== the same query with the SPLIT dates used, as intended ===")
FIXED = FINAL.replace("stg.ROW_EFFECTIVE_DATETIME   AS ROW_EFFECTIVE_DATETIME,     -- line 76: UNSPLIT",
                      "stg.SPLIT_ROW_EFFECTIVE_DATETIME  AS ROW_EFFECTIVE_DATETIME,") \
             .replace("stg.ROW_EXPIRATION_DATETIME  AS ROW_EXPIRATION_DATETIME,    -- line 77: UNSPLIT",
                      "stg.SPLIT_ROW_EXPIRATION_DATETIME AS ROW_EXPIRATION_DATETIME,") \
             .replace("PARTITION BY stg.OFFICE_NUMBER, stg.DEPARTMENT_NUMBER, stg.ROW_EFFECTIVE_DATETIME   -- line 137: UNSPLIT",
                      "PARTITION BY stg.OFFICE_NUMBER, stg.DEPARTMENT_NUMBER, stg.SPLIT_ROW_EFFECTIVE_DATETIME") \
             .replace("ORDER BY stg.ROW_EXPIRATION_DATETIME DESC NULLS LAST", "ORDER BY stg.SPLIT_ROW_EXPIRATION_DATETIME DESC NULLS LAST")
for r in c.execute(FIXED).fetchall(): print("   ", r)
print("   -> two rows, each with its own interval and the office version in force.\n")

print("=== NULL expiry in staging: 'WHERE b IS NOT NULL' was removed ===")
c.execute("DELETE FROM OFFICE_DEPARTMENT_STG")
c.execute("INSERT INTO OFFICE_DEPARTMENT_STG VALUES ('O001','D001','555-0100',DATE '2024-01-01',NULL,'Y')")
n = len(c.execute(CTE + " SELECT * FROM fk_split_stg").fetchall())
print(f"   staging rows: 1 (expiry NULL)   rows surviving the split: {n}")
print("   -> the containment predicate s.ROW_EXPIRATION_DATETIME > fi.ROW_EFFECTIVE_DATETIME is NULL,")
print("      so the row is dropped. Q1's checks 4 and 6 do not catch a NULL expiry either.")
