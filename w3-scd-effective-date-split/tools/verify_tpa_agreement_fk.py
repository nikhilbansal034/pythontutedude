import duckdb
c = duckdb.connect()

# AGREEMENT is SCD-2; AGREEMENT_ID is its PK, so it is unique PER VERSION ROW.
c.execute("""CREATE TABLE AGREEMENT(AGREEMENT_ID INT, SOURCE_AGREEMENT_IDENTIFIER VARCHAR,
             SOURCE_SYSTEM_CODE VARCHAR, AGREEMENT_STATUS_CODE VARCHAR,
             ROW_EFFECTIVE_DATETIME DATE, ROW_EXPIRATION_DATETIME DATE)""")
c.executemany("INSERT INTO AGREEMENT VALUES (?,?,?,?,?,?)", [
    (901,'A1','CCO','ACTIVE'  ,'2024-01-01','2024-04-01'),
    (902,'A1','CCO','ENDORSED','2024-04-01','9999-12-31')])

# One staging interval that SPANS the agreement version boundary at 2024-04-01.
c.execute("""CREATE TABLE STG(SOURCE_TPA_IDENTIFIER VARCHAR, SOURCE_SYSTEM_CODE VARCHAR,
             ROW_EFFECTIVE_DATETIME DATE, ROW_EXPIRATION_DATETIME DATE, DIVISION_CODE VARCHAR)""")
c.execute("INSERT INTO STG VALUES ('A1','CCO',DATE '2024-01-01',DATE '9999-12-31','D1')")

print("=== AS GENERATED: point-in-time match on ROW_EFFECTIVE_DATETIME only ===")
rows = c.execute("""
  SELECT s.SOURCE_TPA_IDENTIFIER, s.ROW_EFFECTIVE_DATETIME, s.ROW_EXPIRATION_DATETIME, a.AGREEMENT_ID
  FROM STG s LEFT JOIN AGREEMENT a
    ON s.SOURCE_TPA_IDENTIFIER = a.SOURCE_AGREEMENT_IDENTIFIER
   AND s.SOURCE_SYSTEM_CODE    = a.SOURCE_SYSTEM_CODE
   AND s.ROW_EFFECTIVE_DATETIME >= a.ROW_EFFECTIVE_DATETIME
   AND s.ROW_EFFECTIVE_DATETIME <  a.ROW_EXPIRATION_DATETIME""").fetchall()
for r in rows: print("  ", r)
print("   -> one row, FK = 901. It stays 901 until 9999-12-31, but 901 expired on 2024-04-01.")
print("      Every query joining this row to AGREEMENT after 2024-04-01 reads status ACTIVE,")
print("      when the agreement was ENDORSED from 2024-04-01. STALE FK CONFIRMED.\n")

print("=== CORRECT: cut the staging interval at AGREEMENT's own version boundaries ===")
fixed = c.execute("""
  WITH bounds AS (
    SELECT s.SOURCE_TPA_IDENTIFIER, s.SOURCE_SYSTEM_CODE, d AS b
    FROM STG s, LATERAL (SELECT UNNEST([s.ROW_EFFECTIVE_DATETIME, s.ROW_EXPIRATION_DATETIME]) AS d)
    UNION
    SELECT s.SOURCE_TPA_IDENTIFIER, s.SOURCE_SYSTEM_CODE, a.ROW_EFFECTIVE_DATETIME
    FROM STG s JOIN AGREEMENT a
      ON s.SOURCE_TPA_IDENTIFIER=a.SOURCE_AGREEMENT_IDENTIFIER AND s.SOURCE_SYSTEM_CODE=a.SOURCE_SYSTEM_CODE
    WHERE a.ROW_EFFECTIVE_DATETIME > s.ROW_EFFECTIVE_DATETIME
      AND a.ROW_EFFECTIVE_DATETIME < s.ROW_EXPIRATION_DATETIME),
  iv AS (SELECT SOURCE_TPA_IDENTIFIER, SOURCE_SYSTEM_CODE, b AS s_eff,
                LEAD(b) OVER (PARTITION BY SOURCE_TPA_IDENTIFIER ORDER BY b) AS s_exp
         FROM bounds)
  SELECT i.SOURCE_TPA_IDENTIFIER, i.s_eff, i.s_exp, a.AGREEMENT_ID, a.AGREEMENT_STATUS_CODE
  FROM iv i JOIN AGREEMENT a
    ON i.SOURCE_TPA_IDENTIFIER=a.SOURCE_AGREEMENT_IDENTIFIER AND i.SOURCE_SYSTEM_CODE=a.SOURCE_SYSTEM_CODE
   AND a.ROW_EFFECTIVE_DATETIME <= i.s_eff AND a.ROW_EXPIRATION_DATETIME >= i.s_exp
  WHERE i.s_exp IS NOT NULL ORDER BY 2""").fetchall()
for r in fixed: print("  ", r)
print("   -> two rows, each with the agreement version actually in force. FK never stale.\n")

print("=== NEW DEFECT: the MERGE key contains a resolved FK surrogate ===")
print("   Generated ON: (SOURCE_SYSTEM_CODE, ROW_EFFECTIVE_DATETIME, EQUAL_NULL(AGREEMENT_ID))")
c.execute("CREATE TABLE TGT AS SELECT 'CCO' AS SOURCE_SYSTEM_CODE, DATE '2024-01-01' AS ROW_EFFECTIVE_DATETIME, 901 AS AGREEMENT_ID")
print("   target already holds the row with AGREEMENT_ID=901.")
print("   AGREEMENT is reloaded and A1's current version becomes a NEW surrogate 903:")
c.execute("UPDATE AGREEMENT SET AGREEMENT_ID=903 WHERE AGREEMENT_ID=901")
m = c.execute("""SELECT COUNT(*) FROM (SELECT 'CCO' AS SOURCE_SYSTEM_CODE, DATE '2024-01-01' AS ROW_EFFECTIVE_DATETIME,
                 (SELECT AGREEMENT_ID FROM AGREEMENT WHERE SOURCE_AGREEMENT_IDENTIFIER='A1' AND ROW_EFFECTIVE_DATETIME='2024-01-01') AS AGREEMENT_ID) src
                 JOIN TGT t ON src.SOURCE_SYSTEM_CODE=t.SOURCE_SYSTEM_CODE
                 AND src.ROW_EFFECTIVE_DATETIME=t.ROW_EFFECTIVE_DATETIME
                 AND src.AGREEMENT_ID IS NOT DISTINCT FROM t.AGREEMENT_ID""").fetchone()[0]
print(f"   rows matching the existing target row: {m}  ->  WHEN NOT MATCHED fires  ->  DUPLICATE INSERT")
