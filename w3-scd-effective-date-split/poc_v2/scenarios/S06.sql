       CASE WHEN (SELECT count(*) FROM STG_Z2_BROKER_PARTY_DIM)  = 2
                   AND (SELECT count(*) FROM STG_Z2_BROKER_PARTY_DIM WHERE RULE_NO = 9) = 2
                   AND (SELECT count(*) FROM Z2_BROKER_PARTY_DIM) = 3
                   AND (SELECT count(*) FROM V_Z2_BROKER_PARTY_DIM_LIVE) = 1
            -- the live row now carries NO tier
                   AND (SELECT count(*) FROM V_Z2_BROKER_PARTY_DIM_LIVE WHERE COMMISSION_TIER_CDE IS NULL) = 1
            -- two dead records now, one per correction
                   AND (SELECT count(*) FROM Z2_BROKER_PARTY_DIM WHERE ROW_EFF_DTE = ROW_EXP_DTE AND IS_DEL = 'N') = 2
